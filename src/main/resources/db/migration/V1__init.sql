CREATE TABLE customer (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_ref      VARCHAR(64)  NOT NULL UNIQUE,
    name              VARCHAR(128) NOT NULL,
    country_code      VARCHAR(2)   NOT NULL,
    occupation_risk   VARCHAR(16)  NOT NULL,
    pep               BOOLEAN      NOT NULL,
    national_id_token VARCHAR(128),
    phone             VARCHAR(32),
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE txn (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id          VARCHAR(64)    NOT NULL UNIQUE,
    customer_id          BIGINT         NOT NULL REFERENCES customer (id),
    amount               NUMERIC(18, 2) NOT NULL,
    channel              VARCHAR(16)    NOT NULL,
    direction            VARCHAR(16)    NOT NULL,
    counterparty_country VARCHAR(2),
    occurred_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_txn_customer_time ON txn (customer_id, occurred_at);
CREATE INDEX idx_txn_channel_time ON txn (channel, occurred_at);

CREATE TABLE alert (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version      BIGINT       NOT NULL,
    customer_id  BIGINT       NOT NULL REFERENCES customer (id),
    rule_code    VARCHAR(32)  NOT NULL,
    dedupe_key   VARCHAR(128) NOT NULL UNIQUE,
    score        INT          NOT NULL,
    severity     VARCHAR(16)  NOT NULL,
    status       VARCHAR(32)  NOT NULL,
    reason       VARCHAR(512) NOT NULL,
    assignee     VARCHAR(64),
    escalated_by VARCHAR(64),
    closing_note VARCHAR(1024),
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_alert_status ON alert (status, created_at);
CREATE INDEX idx_alert_customer ON alert (customer_id, created_at);

CREATE TABLE alert_txn (
    alert_id BIGINT NOT NULL REFERENCES alert (id),
    txn_id   BIGINT NOT NULL REFERENCES txn (id),
    PRIMARY KEY (alert_id, txn_id)
);

CREATE TABLE ctr_report (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version           BIGINT         NOT NULL,
    customer_id       BIGINT         NOT NULL REFERENCES customer (id),
    business_date     DATE           NOT NULL,
    direction         VARCHAR(16)    NOT NULL,
    total_amount      NUMERIC(18, 2) NOT NULL,
    txn_count         INT            NOT NULL,
    status            VARCHAR(16)    NOT NULL,
    national_id_token VARCHAR(128),
    phone             VARCHAR(32),
    submitted_by      VARCHAR(64),
    updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_ctr UNIQUE (customer_id, business_date, direction)
);

CREATE TABLE audit_event (
    seq         BIGINT       NOT NULL PRIMARY KEY,
    actor       VARCHAR(64)  NOT NULL,
    action      VARCHAR(64)  NOT NULL,
    entity_type VARCHAR(32)  NOT NULL,
    entity_id   VARCHAR(64)  NOT NULL,
    detail      VARCHAR(1024) NOT NULL,
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    prev_hash   VARCHAR(64)  NOT NULL,
    hash        VARCHAR(64)  NOT NULL
);

-- Single row that serializes writers of the audit hash chain.
CREATE TABLE audit_head (
    id        INT         NOT NULL PRIMARY KEY,
    last_seq  BIGINT      NOT NULL,
    last_hash VARCHAR(64) NOT NULL
);
